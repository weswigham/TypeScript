type Transformation = (n: Node, t: Transformation) => Node;

function setCommonFields(clone: Node, pos: number, end: number, flags: number, modifierFlags: number, transformFlags: number) {
    (clone as Mutable<Node>).pos = pos;
    (clone as Mutable<Node>).end = end;
    (clone as Mutable<Node>).flags = flags;
    (clone as Mutable<Node>).modifierFlagsCache = modifierFlags;
    (clone as Mutable<Node>).transformFlags = transformFlags;
    return clone;
}

